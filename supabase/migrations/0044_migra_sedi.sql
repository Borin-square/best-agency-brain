-- aree, citta e regioni calcolati dalle sedi italiane (la principale per prima).
create or replace function public.aggiorna_testi_geo(p_agency_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  with sedi as (
    select s.principale, p.slug as provincia_slug, p.nome as provincia, r.slug as regione_slug, r.nome as regione
    from public.agency_sedi s
    join public.areas p on p.id = s.area_id
    join public.areas r on r.id = p.parent_id
    where s.agency_id = p_agency_id
  ),
  testi as (
    select string_agg(regione || '>' || provincia, ', ' order by principale desc, provincia) as aree,
           (select provincia_slug from sedi where principale limit 1) as citta,
           (select regione_slug from sedi where principale limit 1) as regioni
    from sedi
  )
  update public.agencies g
  set aree = t.aree, citta = t.citta, regioni = t.regioni
  from testi t
  where g.id = p_agency_id
    and (g.aree, g.citta, g.regioni) is distinct from (t.aree, t.citta, t.regioni);
$$;

create or replace function public.agency_sedi_dopo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    perform public.allinea_agency_areas_da_sedi(old.agency_id);
    perform public.aggiorna_testi_geo(old.agency_id);
  end if;
  if tg_op in ('INSERT', 'UPDATE') and (tg_op = 'INSERT' or new.agency_id <> old.agency_id) then
    perform public.allinea_agency_areas_da_sedi(new.agency_id);
    perform public.aggiorna_testi_geo(new.agency_id);
  end if;
  return null;
end
$$;

drop trigger if exists agency_sedi_dopo on public.agency_sedi;
create trigger agency_sedi_dopo
  after insert or update or delete on public.agency_sedi
  for each row execute function public.agency_sedi_dopo();

